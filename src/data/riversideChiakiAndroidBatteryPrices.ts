export function getRiversideChiakiAndroidBatteryPrice(
  storeName: string,
  modelName: string,
) {
  if (storeName !== RIVERSIDE_CHIAKI_STORE_NAME) {
    return undefined;
  }

  return RIVERSIDE_CHIAKI_ANDROID_BATTERY_PRICES.get(modelName);
}

export function getRiversideChiakiBatteryOnlyAndroidModels(storeName: string) {
  return storeName === RIVERSIDE_CHIAKI_STORE_NAME
    ? RIVERSIDE_CHIAKI_BATTERY_ONLY_ANDROID_MODELS
    : [];
}

export function isRiversideChiakiBatteryOnlyAndroidModel(
  storeName: string,
  item: AndroidPriceMasterItem | undefined,
) {
  return (
    storeName === RIVERSIDE_CHIAKI_STORE_NAME &&
    Boolean(
      item &&
        RIVERSIDE_CHIAKI_BATTERY_ONLY_ANDROID_MODEL_NAMES.has(item.modelName),
    )
  );
}
